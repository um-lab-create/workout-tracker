// キーを長い順に（「豚肉」を「豚」より先に置換するため）
const SEARCH_ALIAS_KEYS = Object.keys(SEARCH_ALIASES).sort((a, b) => b.length - a.length);

/**
 * 検索クエリのバリアント（別解釈の文字列）を返す。
 * 例: '豚バラ' → ['豚バラ', ' ぶた バラ']（後者はトークン分割されて AND マッチに使われる）
 * 複数読みキーが含まれる場合は第2読みのバリアントも足す（最大3つ）。
 * @param {string} q 生クエリ
 * @returns {string[]} バリアント（先頭は原文）
 */
function buildQueryVariants(q) {
  const variants = [q];
  let primary = q;
  let hasMulti = false;
  for (const key of SEARCH_ALIAS_KEYS) {
    if (!primary.includes(key)) continue;
    const readings = SEARCH_ALIASES[key];
    if (readings.length > 1) hasMulti = true;
    // 置換後は空白で区切り、後段のトークンAND検索が「ぶた」「ばら」に分けて効くようにする
    primary = primary.split(key).join(` ${readings[0]} `);
  }
  if (primary !== q) variants.push(primary);
  if (hasMulti) {
    let secondary = q;
    for (const key of SEARCH_ALIAS_KEYS) {
      if (!secondary.includes(key)) continue;
      const readings = SEARCH_ALIASES[key];
      secondary = secondary.split(key).join(` ${readings[1] || readings[0]} `);
    }
    if (secondary !== q && secondary !== primary) variants.push(secondary);
  }
  return variants;
}
